"""Twemoji -> the receive-side emoji sprites.

    python tools/gen_emoji.py

Downloads each listed emoji from the Twemoji set (72x72 PNG), scales it to
PX x PX, and writes
    include/emoji_cp.h    code points + the helpers that need no screen
    src/emoji_data.cpp    the pixels, RGB565 with a colour key for "clear"

Edit LIST to change the set (94 at most: a token is 0x01 then 0x20 + index).
Twemoji graphics are (c) Twitter, Inc and other contributors, CC-BY 4.0
(https://creativecommons.org/licenses/by/4.0/), from github.com/jdecked/twemoji.
"""
import io, os, sys, urllib.request
from PIL import Image

PX = 14
KEY = 0xF81F            # magenta: transparent. A real pixel that lands on it is nudged.
BASE = 'https://raw.githubusercontent.com/jdecked/twemoji/main/assets/72x72/%s.png'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

LIST = [
    # faces
    0x1F600, 0x1F601, 0x1F602, 0x1F603, 0x1F604, 0x1F605, 0x1F606, 0x1F607, 0x1F609, 0x1F60A,
    0x1F60B, 0x1F60D, 0x1F60E, 0x1F60F, 0x1F610, 0x1F612, 0x1F614, 0x1F618, 0x1F61C, 0x1F620,
    0x1F621, 0x1F622, 0x1F62D, 0x1F62E, 0x1F631, 0x1F634, 0x1F642, 0x1F643, 0x1F644, 0x1F914,
    0x1F917, 0x1F923, 0x1F929, 0x1F970, 0x1F975, 0x1F976,
    # hands
    0x1F44D, 0x1F44E, 0x1F44B, 0x1F44F, 0x1F44C, 0x1F44A, 0x270C, 0x1F64F, 0x1F64C, 0x1F4AA,
    0x1F91D,
    # hearts, marks, fire
    0x2764, 0x1F494, 0x1F496, 0x1F499, 0x1F49A, 0x1F49B, 0x1F49C, 0x1F4AF, 0x1F4A5,
    0x1F4A9, 0x1F480, 0x1F47B, 0x1F525, 0x2728, 0x2B50, 0x1F389, 0x1F381,
    0x1F440, 0x1F4A1, 0x1F4A4,
    # weather, places
    0x2600, 0x2601, 0x2744, 0x26A1, 0x1F308, 0x1F30A, 0x1F332, 0x1F33B, 0x1F30D,
    0x1F3E0, 0x1F697, 0x26F0,
    # things
    0x1F680, 0x1F4E1, 0x1F50B, 0x1F4BB, 0x1F4F1, 0x1F37A, 0x2615, 0x1F355, 0x1F382,
    # signs
    0x2705, 0x274C, 0x26A0, 0x2753, 0x2757, 0x1F6A8,
]
assert len(set(LIST)) == len(LIST) and len(LIST) <= 94, len(LIST)


def sprite(cp):
    url = BASE % ('%x' % cp)
    with urllib.request.urlopen(url, timeout=30) as r:
        im = Image.open(io.BytesIO(r.read())).convert('RGBA')
    im = im.resize((PX, PX), Image.LANCZOS)
    out = []
    for y in range(PX):
        for x in range(PX):
            r, g, b, a = im.getpixel((x, y))
            if a < 110:
                out.append(KEY)
                continue
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            if v == KEY:
                v ^= 0x0020
            out.append(v)
    return out


def main():
    ok = []
    for cp in LIST:
        try:
            ok.append((cp, sprite(cp)))
        except Exception as e:
            print('skipped U+%X: %s' % (cp, e), file=sys.stderr)
    n = len(ok)
    hdr = os.path.join(ROOT, 'include', 'emoji_cp.h')
    with open(hdr, 'w', newline='\n') as f:
        f.write('''// SquachWatch-CYD -- the emoji this board can draw. GENERATED by tools/gen_emoji.py.
//
// Received emoji that are in this set become a two-byte token in message text:
// TOKEN (0x01) then 0x20 + the index below. Anything else folds to '?'
// (Pb::asciiFold). The compose line holds the same tokens and turns them back
// into UTF-8 when a message is sent (expand()). Artwork: Twemoji, (c) Twitter,
// Inc and other contributors, CC-BY 4.0, https://creativecommons.org/licenses/by/4.0/
//
// Header-only and screen-free so the host tests share it.
#pragma once
#include <stdint.h>
#include <stddef.h>

namespace Emoji {

static const uint8_t TOKEN = 0x01;
static const uint8_t PX = %d;                 // sprites are PX x PX
static const uint8_t COUNT = %d;
static const uint32_t CP[COUNT] = {
''' % (PX, n))
        for i in range(0, n, 8):
            f.write('    ' + ', '.join('0x%X' % cp for cp, _ in ok[i:i + 8]) + ',\n')
        f.write('''};

// The index of a code point, or -1.
inline int indexOf(uint32_t cp) {
    for (uint8_t i = 0; i < COUNT; i++) if (CP[i] == cp) return i;
    return -1;
}
// An emoji we have no picture for: the same two-byte shape, with this fixed
// second byte (above the last sprite's, 0x20 + COUNT - 1, which is why COUNT
// is at most 94). Drawn as a small "?" tile by emoji_draw.cpp.
static const uint8_t PLACEHOLDER = 0x7E;
inline bool isPlaceholder(const char* s) {
    return (uint8_t)s[0] == TOKEN && (uint8_t)s[1] == PLACEHOLDER;
}
inline bool isToken(const char* s) {
    return isPlaceholder(s) || ((uint8_t)s[0] == TOKEN && (uint8_t)s[1] >= 0x20 && (uint8_t)s[1] < 0x20 + COUNT);
}
// Only for a token that is not the placeholder.
inline uint8_t tokenIndex(const char* s) { return (uint8_t)s[1] - 0x20; }

// Tokens back to '?' for a screen that does not draw them (a list preview, a
// log line), in place.
inline void plain(char* s) {
    char* w = s;
    for (const char* r = s; *r; ) {
        if (isToken(r)) { *w++ = '?'; r += 2; }
        else if ((uint8_t)*r == TOKEN) r++;
        else *w++ = *r++;
    }
    *w = '\\0';
}

// Tokens to UTF-8 for the air. Room for the worst case is 4 bytes per token.
inline size_t expand(const char* in, char* out, size_t cap) {
    size_t o = 0;
    if (!cap) return 0;
    for (const char* r = in; *r && o + 5 < cap; ) {
        if (isPlaceholder(r)) { out[o++] = '?'; r += 2; }
        else if (isToken(r)) {
            const uint32_t cp = CP[tokenIndex(r)];
            r += 2;
            if (cp >= 0x10000) { out[o++] = (char)(0xF0 | (cp >> 18)); out[o++] = (char)(0x80 | ((cp >> 12) & 0x3F)); out[o++] = (char)(0x80 | ((cp >> 6) & 0x3F)); out[o++] = (char)(0x80 | (cp & 0x3F)); }
            else { out[o++] = (char)(0xE0 | (cp >> 12)); out[o++] = (char)(0x80 | ((cp >> 6) & 0x3F)); out[o++] = (char)(0x80 | (cp & 0x3F)); }
        } else if ((uint8_t)*r == TOKEN) r++;
        else out[o++] = *r++;
    }
    out[o] = '\\0';
    return o;
}

// The pixels (emoji_data.cpp): PX*PX RGB565, KEY where clear.
static const uint16_t KEY = 0x%04X;
extern const uint16_t PIXELS[COUNT][PX * PX];

}  // namespace Emoji
''' % KEY)
    src = os.path.join(ROOT, 'src', 'emoji_data.cpp')
    with open(src, 'w', newline='\n') as f:
        f.write('// GENERATED by tools/gen_emoji.py -- do not edit. Artwork: Twemoji, (c) Twitter, Inc and\n'
                '// other contributors, CC-BY 4.0 (https://creativecommons.org/licenses/by/4.0/).\n'
                '#include "emoji_cp.h"\n'
                '#if SQUACH_LORA || SQUACH_LORA_FAKE\n'
                'namespace Emoji {\n'
                'const uint16_t PIXELS[COUNT][PX * PX] = {\n')
        for cp, px in ok:
            f.write('    { // U+%X\n' % cp)
            for i in range(0, len(px), 14):
                f.write('        ' + ','.join('0x%04X' % v for v in px[i:i + 14]) + ',\n')
            f.write('    },\n')
        f.write('};\n}  // namespace Emoji\n#endif\n')
    print('wrote %d emoji, %d bytes of pixels' % (n, n * PX * PX * 2))


main()
