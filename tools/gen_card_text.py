#!/usr/bin/env python3
"""tools/card_text.json -> src/card_text.inc: the info card's headline, WHY,
TIP and kind colours, included by src/detection_info.cpp.

    python tools/gen_card_text.py

Edit the JSON (the wording page exports it), then run this. The colours are
snapped to ones an 8-bit (RGB332) frame holds exactly, so nothing bands."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'card_text.inc')
data = json.load(open(os.path.join(HERE, 'card_text.json'), encoding='utf-8'))

LV = [0, 36, 73, 109, 146, 182, 219, 255]
LB = [0, 85, 170, 255]
def snap565(hexcol):
    r, g, b = int(hexcol[1:3], 16), int(hexcol[3:5], 16), int(hexcol[5:7], 16)
    r = min(LV, key=lambda v: abs(v - r)); g = min(LV, key=lambda v: abs(v - g)); b = min(LB, key=lambda v: abs(v - b))
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

L = ['// GENERATED by tools/gen_card_text.py from tools/card_text.json -- edit the JSON, not this.',
     '// The info card\'s three short lines and its colours, per DetectionType (enum order)',
     '// and per device page (by DeviceInfo title). Included by detection_info.cpp.',
     '',
     'static const CardType CARD_TYPES[] = {']
for t in data['types']:
    a, b = snap565(t['kind'][0]), snap565(t['kind'][1])
    L.append(f'    // {t["key"]}')
    L.append(f'    {{ {q(t["head"])}, {q(t["why"])}, {q(t["tip"])}, 0x{a:04X}, 0x{b:04X} }},')
L.append('};')
L.append('')
L.append('static const CardPage CARD_PAGES[] = {')
for d in data['devices']:
    titles = ['AXON BODY 2', 'AXON BODY 3', 'AXON BODY 4'] if d['title'].startswith('AXON BODY 2') else [d['title']]
    for title in titles:
        L.append(f'    {{ {q(title)}, {q(d["head"])}, {q(d["why"])}, {q(d["tip"])} }},')
L.append('};')
# Every device page in src/device_info.cpp needs its lines here: a page
# without them would quietly fall back to its type's. And nothing longer
# than the watch shows on one or two lines.
import re
dv = open(os.path.join(HERE, '..', 'src', 'device_info.cpp'), encoding='utf-8').read()
titles = re.findall(r'\{\s*DetectionType::\w+,\s*"([^"]+)"', dv)
have = set()
for d in data['devices']:
    have.update(['AXON BODY 2', 'AXON BODY 3', 'AXON BODY 4'] if d['title'].startswith('AXON BODY 2') else [d['title']])
missing = [t for t in titles if t not in have]
if missing:
    raise SystemExit('card_text.json has no lines for device pages: ' + ', '.join(missing))
for r in data['types'] + data['devices']:
    for f, lim in (('head', 32), ('why', 30), ('tip', 62)):
        if len(r[f]) > lim:
            raise SystemExit(f"{r.get('title', r.get('key'))}: {f} is {len(r[f])} long (the watch fits {lim})")

open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
print('wrote', OUT, len(data['types']), 'types', sum(3 if d['title'].startswith('AXON BODY 2') else 1 for d in data['devices']), 'pages')
